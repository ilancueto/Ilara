CREATE TABLE public.sale_item_components (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_item_id bigint NOT NULL REFERENCES public.sale_items(id) ON DELETE CASCADE,
  product_id bigint REFERENCES public.products(id) ON DELETE SET NULL,
  product_name text NOT NULL,
  quantity_per_unit integer NOT NULL CHECK (quantity_per_unit > 0),
  snapshot_source text NOT NULL
    CHECK (snapshot_source IN ('sale_time', 'legacy_product', 'legacy_current_combo')),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (sale_item_id, product_id)
);

CREATE INDEX sale_item_components_sale_item_idx
  ON public.sale_item_components (sale_item_id);
CREATE INDEX sale_item_components_product_idx
  ON public.sale_item_components (product_id);

CREATE TABLE public.sale_returns (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  credit_note_number bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE NOT NULL,
  sale_id bigint NOT NULL REFERENCES public.sales(id) ON DELETE RESTRICT,
  status text NOT NULL DEFAULT 'completed' CHECK (status = 'completed'),
  reason text NOT NULL CHECK (char_length(trim(reason)) BETWEEN 3 AND 500),
  refund_method text NOT NULL CHECK (
    refund_method IN (
      'efectivo', 'transferencia', 'tarjeta', 'mercadopago',
      'credito_cancelado', 'otro'
    )
  ),
  refund_total numeric(12,2) NOT NULL CHECK (refund_total > 0),
  restock boolean NOT NULL DEFAULT true,
  idempotency_key uuid NOT NULL UNIQUE,
  created_by uuid NOT NULL REFERENCES auth.users(id),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX sale_returns_sale_created_idx
  ON public.sale_returns (sale_id, created_at DESC);
CREATE INDEX sale_returns_created_idx
  ON public.sale_returns (created_at DESC);
CREATE INDEX sale_returns_created_by_idx
  ON public.sale_returns (created_by);

CREATE TABLE public.sale_return_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  return_id uuid NOT NULL REFERENCES public.sale_returns(id) ON DELETE RESTRICT,
  sale_item_id bigint NOT NULL REFERENCES public.sale_items(id) ON DELETE RESTRICT,
  product_id bigint,
  product_name text NOT NULL,
  quantity integer NOT NULL CHECK (quantity > 0),
  unit_price numeric(12,2) NOT NULL CHECK (unit_price >= 0),
  refund_amount numeric(12,2) NOT NULL CHECK (refund_amount > 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (return_id, sale_item_id)
);

CREATE INDEX sale_return_items_return_idx
  ON public.sale_return_items (return_id);
CREATE INDEX sale_return_items_sale_item_idx
  ON public.sale_return_items (sale_item_id);
CREATE INDEX sale_return_items_product_idx
  ON public.sale_return_items (product_id);

CREATE TABLE public.sale_return_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  return_id uuid NOT NULL REFERENCES public.sale_returns(id) ON DELETE RESTRICT,
  event_type text NOT NULL CHECK (event_type IN ('created')),
  actor_user_id uuid NOT NULL REFERENCES auth.users(id),
  meta jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX sale_return_events_return_idx
  ON public.sale_return_events (return_id, created_at);
CREATE INDEX sale_return_events_actor_idx
  ON public.sale_return_events (actor_user_id);

